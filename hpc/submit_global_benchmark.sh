#!/usr/bin/env bash
# One-command Slurm launcher for Global Metagenome Benchmarking (remote ENA reads + pre-made assemblies).
#
# Step 1 — Build a curated manifest on your login node (~20 s):
#   python3 hpc/fetch_global_manifest.py --year 2023 --per-biome 200 --max-per-study 50 \
#       --check-assembler --check-logan -o global_2023.tsv
#
# Step 2 — Run a 1-sample pilot first (preview with --dry-run):
#   bash hpc/submit_global_benchmark.sh \
#       --manifest global_2023.tsv --kma-db /db/resfinder_kma --kma-ref-fa /db/resfinder.fa \
#       --out /scratch/$USER/argj_global_2023 --limit 1 --dry-run
#
# Step 3 — Launch full array (cap --max-concurrent 15 so ENA/S3 never rate-limits downloads):
#   bash hpc/submit_global_benchmark.sh \
#       --manifest global_2023.tsv --kma-db /db/resfinder_kma --kma-ref-fa /db/resfinder.fa \
#       --out /scratch/$USER/argj_global_2023 --partition standard --account myproj \
#       --cpus 8 --mem 24G --time 02:00:00 --max-concurrent 15

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

MANIFEST_TSV=""
GENES_FA=""
KMA_DB=""
KMA_REF_FA=""
OUT_DIR=""
PARTITION=""
ACCOUNT=""
QOS=""
CPUS=8
MEM="24G"
TIME="02:00:00"
POST_CPUS=4
POST_MEM="24G"
POST_TIME="04:00:00"
ANN_CPUS=16
ANN_MEM="64G"
ANN_TIME="06:00:00"
DB_ENV=""
MAX_CONCURRENT=15
LIMIT=0
FLANK_BP=10000
COHORT_PAIR_BP=500
COHORT_MIN_SAMPLES=4
ASM_ALIGNER="auto"
EXTRA_ARGS=""
ENV_SETUP_CMD=""
SKIP_FASTP=0
SKIP_ASSEMBLY=0
USE_LOGAN=0
NO_COHORT=0
FORCE=0
RESUBMIT_MISSING=0
DRY_RUN=0

usage() {
    cat <<'EOF'
Usage: bash hpc/submit_global_benchmark.sh --manifest global_manifest.tsv --out OUT_DIR [options]

Required:
  --manifest FILE         Manifest TSV generated by hpc/fetch_global_manifest.py
  --out DIR               Output directory (writes samples/, cohorts/, comparison/, summary/, logs/)

Gene source (provide one):
  --kma-db PREFIX         Recommended: KMA ResFinder/CARD database for per-sample ARG pre-screening
  --kma-ref-fa FILE       Optional reference FASTA matching --kma-db
  --genes FILE            Alternative: shared target genes FASTA passed directly to ARGjacent

Slurm resources:
  --partition NAME        Slurm partition (-p)
  --account NAME          Slurm account (-A)
  --qos NAME              Slurm QoS (--qos)
  --cpus N                CPUs per sample task (default: 8)
  --mem SIZE              RAM per sample task (default: 24G)
  --time HH:MM:SS         Walltime per sample task (default: 02:00:00)
  --max-concurrent N      Max simultaneous downloading/running tasks (default: 15; keep <=20 for ENA)
  --post-cpus N           CPUs for post-array cohort+comparison job (default: 4)
  --post-mem SIZE         RAM for post-array job (default: 24G)
  --post-time HH:MM:SS    Walltime for post-array job (default: 04:00:00)
  --db-env FILE           Optional db_paths.env (from setup_annotation_dbs.sh) to auto-chain run_annotate.sbatch
  --ann-cpus N            CPUs for annotation job when --db-env is set (default: 16)
  --ann-mem SIZE          RAM for annotation job when --db-env is set (default: 64G)
  --ann-time HH:MM:SS     Walltime for annotation job when --db-env is set (default: 06:00:00)

Workflow options:
  --limit N               Submit only first N rows (great for 1- or 5-sample HPC pilot)
  --flank-bp BP           Flank target length for both ARGjacent and assemblies (default: 10000)
  --use-logan             Compare against Logan S3 contigs instead of ENA ERZ assemblies (where present)
  --asm-aligner MODE      Assembly gene finder: auto|minimap2|blastn|kmer (default: auto)
  --skip-fastp            Skip fastp trimming (use raw ENA FASTQs directly)
  --skip-assembly         Run ARGjacent only (skip downloading/comparing pre-made assemblies)
  --cohort-min-samples N  Min completed samples per BioProject to trigger argjacent-cohort (default: 4)
  --no-cohort             Skip per-BioProject argjacent-cohort runs
  --extra-args "ARGS"     Extra flags passed to argjacent (e.g. "-w 40")
  --env-cmd "CMD"         Shell command run first inside Slurm jobs (modules / conda activate)
  --force                 Re-run samples even if .done marker exists
  --resubmit-missing      Submit ONLY array indices without a completed .done marker
  --dry-run               Validate manifest and print sbatch commands without submitting
  -h, --help              Show this help
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --manifest)           MANIFEST_TSV="$2"; shift 2 ;;
        --genes)              GENES_FA="$2"; shift 2 ;;
        --kma-db)             KMA_DB="$2"; shift 2 ;;
        --kma-ref-fa)         KMA_REF_FA="$2"; shift 2 ;;
        --out)                OUT_DIR="$2"; shift 2 ;;
        --partition)          PARTITION="$2"; shift 2 ;;
        --account)            ACCOUNT="$2"; shift 2 ;;
        --qos)                QOS="$2"; shift 2 ;;
        --cpus)               CPUS="$2"; shift 2 ;;
        --mem)                MEM="$2"; shift 2 ;;
        --time)               TIME="$2"; shift 2 ;;
        --post-cpus)          POST_CPUS="$2"; shift 2 ;;
        --post-mem)           POST_MEM="$2"; shift 2 ;;
        --post-time)          POST_TIME="$2"; shift 2 ;;
        --db-env)             DB_ENV="$2"; shift 2 ;;
        --ann-cpus)           ANN_CPUS="$2"; shift 2 ;;
        --ann-mem)            ANN_MEM="$2"; shift 2 ;;
        --ann-time)           ANN_TIME="$2"; shift 2 ;;
        --max-concurrent)     MAX_CONCURRENT="$2"; shift 2 ;;
        --limit)              LIMIT="$2"; shift 2 ;;
        --flank-bp)           FLANK_BP="$2"; shift 2 ;;
        --use-logan)          USE_LOGAN=1; shift ;;
        --asm-aligner)        ASM_ALIGNER="$2"; shift 2 ;;
        --skip-fastp)         SKIP_FASTP=1; shift ;;
        --skip-assembly)      SKIP_ASSEMBLY=1; shift ;;
        --cohort-min-samples) COHORT_MIN_SAMPLES="$2"; shift 2 ;;
        --no-cohort)          NO_COHORT=1; shift ;;
        --extra-args)         EXTRA_ARGS="$2"; shift 2 ;;
        --env-cmd)            ENV_SETUP_CMD="$2"; shift 2 ;;
        --force)              FORCE=1; shift ;;
        --resubmit-missing)   RESUBMIT_MISSING=1; shift ;;
        --dry-run)            DRY_RUN=1; shift ;;
        -h|--help)            usage; exit 0 ;;
        *)                    echo "Unknown option: $1" >&2; usage; exit 1 ;;
    esac
done

if [[ -z "$MANIFEST_TSV" || -z "$OUT_DIR" ]]; then
    echo "ERROR: --manifest and --out are required." >&2
    usage
    exit 1
fi

MANIFEST_ABS="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$MANIFEST_TSV")"
OUT_ABS="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$OUT_DIR")"
[[ -s "$MANIFEST_ABS" ]] || { echo "ERROR: manifest not found or empty: $MANIFEST_ABS" >&2; exit 1; }

GENES_ABS=""
if [[ -n "$GENES_FA" ]]; then
    GENES_ABS="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$GENES_FA")"
    [[ -s "$GENES_ABS" ]] || { echo "ERROR: --genes file not found or empty: $GENES_ABS" >&2; exit 1; }
fi

DB_ENV_ABS=""
if [[ -n "$DB_ENV" ]]; then
    DB_ENV_ABS="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$DB_ENV")"
    [[ -s "$DB_ENV_ABS" ]] || { echo "ERROR: --db-env file not found or empty: $DB_ENV_ABS" >&2; exit 1; }
fi

# Validate manifest columns and count rows
N_TOTAL="$(python3 - "$MANIFEST_ABS" <<'PY'
import sys
with open(sys.argv[1]) as fh:
    hdr = [c.strip() for c in fh.readline().rstrip("\r\n").split("\t")]
    if "sample" not in hdr or not (("r1_url" in hdr and "r2_url" in hdr) or ("r1" in hdr and "r2" in hdr)):
        sys.exit(f"ERROR: manifest must contain 'sample' and ('r1_url','r2_url') or ('r1','r2'); found: {hdr}")
    n = sum(1 for l in fh if l.strip() and not l.startswith("#"))
    if n == 0:
        sys.exit("ERROR: manifest contains 0 sample rows.")
    print(n)
PY
)"

HAS_GCOL="$(python3 -c 'import sys; h=[c.strip() for c in open(sys.argv[1]).readline().rstrip("\r\n").split("\t")]; print("1" if "genes_fa" in h else "0")' "$MANIFEST_ABS")"
if [[ -z "$GENES_ABS" && -z "$KMA_DB" && "$HAS_GCOL" != "1" ]]; then
    echo "ERROR: provide --kma-db PREFIX, --genes FILE, or a 'genes_fa' column in $MANIFEST_ABS" >&2
    exit 1
fi

if [[ "$LIMIT" -gt 0 && "$LIMIT" -lt "$N_TOTAL" ]]; then
    N_RUN="$LIMIT"
else
    N_RUN="$N_TOTAL"
fi

if [[ "$RESUBMIT_MISSING" == "1" ]]; then
    ARRAY_SPEC="$(python3 - "$MANIFEST_ABS" "$OUT_ABS" "$N_RUN" <<'PY'
import os, sys
tsv, out_dir, limit = sys.argv[1], sys.argv[2], int(sys.argv[3])
miss = []
with open(tsv) as fh:
    hdr = [c.strip() for c in fh.readline().rstrip("\r\n").split("\t")]
    scol = hdr.index("sample")
    idx = 0
    for line in fh:
        if not line.strip() or line.startswith("#"):
            continue
        idx += 1
        if idx > limit:
            break
        sid = line.rstrip("\r\n").split("\t")[scol].strip()
        sdir = os.path.join(out_dir, "samples", sid)
        if not (os.path.isfile(os.path.join(sdir, f"{sid}.done")) and os.path.isfile(os.path.join(sdir, f"{sid}.flanks.json"))):
            miss.append(str(idx))
print(",".join(miss))
PY
)"
    if [[ -z "$ARRAY_SPEC" ]]; then
        echo "All ${N_RUN} samples in ${OUT_ABS} are already complete! Nothing to resubmit."
        exit 0
    fi
    ARRAY_SPEC="${ARRAY_SPEC}%${MAX_CONCURRENT}"
else
    ARRAY_SPEC="1-${N_RUN}%${MAX_CONCURRENT}"
fi

LOG_DIR="${OUT_ABS}/logs"
mkdir -p "$OUT_ABS" "$LOG_DIR"

COMMON_SBATCH=()
[[ -n "$PARTITION" ]] && COMMON_SBATCH+=(--partition="$PARTITION")
[[ -n "$ACCOUNT" ]]   && COMMON_SBATCH+=(--account="$ACCOUNT")
[[ -n "$QOS" ]]       && COMMON_SBATCH+=(--qos="$QOS")

export REPO_ROOT="$REPO_ROOT"
export HPC_DIR="$SCRIPT_DIR"
export MANIFEST_TSV="$MANIFEST_ABS"
export OUT_DIR="$OUT_ABS"
export GENES_FA="$GENES_ABS"
export KMA_DB="$KMA_DB"
export KMA_REF_FA="$KMA_REF_FA"
export FLANK_BP="$FLANK_BP"
export SKIP_FASTP="$SKIP_FASTP"
export SKIP_ASSEMBLY="$SKIP_ASSEMBLY"
export USE_LOGAN="$USE_LOGAN"
export ASM_ALIGNER="$ASM_ALIGNER"
export COHORT_PAIR_BP="$COHORT_PAIR_BP"
export COHORT_MIN_SAMPLES="$COHORT_MIN_SAMPLES"
export SKIP_COHORT="$NO_COHORT"
export EXTRA_ARGS="$EXTRA_ARGS"
export FORCE="$FORCE"
export ENV_SETUP_CMD="$ENV_SETUP_CMD"
export DB_ENV="$DB_ENV_ABS"

ARRAY_CMD=(
    sbatch --parsable
    ${COMMON_SBATCH[@]+"${COMMON_SBATCH[@]}"}
    --job-name="argj_global"
    --array="$ARRAY_SPEC"
    --cpus-per-task="$CPUS"
    --mem="$MEM"
    --time="$TIME"
    --output="${LOG_DIR}/argj_global_%A_%a.out"
    --error="${LOG_DIR}/argj_global_%A_%a.err"
    --export=ALL
    "${SCRIPT_DIR}/run_global_array.sbatch"
)

POST_CMD_BASE=(
    sbatch --parsable
    ${COMMON_SBATCH[@]+"${COMMON_SBATCH[@]}"}
    --job-name="argj_global_post"
    --cpus-per-task="$POST_CPUS"
    --mem="$POST_MEM"
    --time="$POST_TIME"
    --output="${LOG_DIR}/argj_global_post_%j.out"
    --error="${LOG_DIR}/argj_global_post_%j.err"
    --export=ALL
)

ANN_CMD_BASE=(
    sbatch --parsable
    ${COMMON_SBATCH[@]+"${COMMON_SBATCH[@]}"}
    --job-name="argj_annotate"
    --cpus-per-task="$ANN_CPUS"
    --mem="$ANN_MEM"
    --time="$ANN_TIME"
    --output="${LOG_DIR}/argj_annotate_%j.out"
    --error="${LOG_DIR}/argj_annotate_%j.err"
    --export=ALL
)

echo "=== ARGjacent Global Metagenome Benchmark Plan ==="
echo "  Manifest       : ${MANIFEST_ABS} (${N_RUN} / ${N_TOTAL} samples, array=${ARRAY_SPEC})"
echo "  Output dir     : ${OUT_ABS}"
echo "  Gene source    : ${KMA_DB:+KMA db ${KMA_DB}}${GENES_ABS:+${KMA_DB:+ + }${GENES_ABS}}"
echo "  Pre-made asm   : $( [[ "$SKIP_ASSEMBLY" == "1" ]] && echo "disabled" || ([[ "$USE_LOGAN" == "1" ]] && echo "Logan S3 contigs (fallback ENA ERZ)" || echo "ENA/MGnify ERZ contigs") ) (aligner=${ASM_ALIGNER})"
echo "  Array resources: ${CPUS} CPUs, ${MEM} RAM, ${TIME} walltime (max ${MAX_CONCURRENT} concurrent)"
echo "  Post-job       : summary + per-BioProject cohort (min ${COHORT_MIN_SAMPLES}) + global assembly comparison"
[[ -n "$DB_ENV_ABS" ]] && echo "  Annotation job : auto-chained with ${DB_ENV_ABS} (${ANN_CPUS} CPUs, ${ANN_MEM} RAM, ${ANN_TIME})"

if [[ "$DRY_RUN" == "1" ]]; then
    echo ""
    echo "[DRY RUN] Array command:"
    printf "  %q" "${ARRAY_CMD[@]}"; echo ""
    echo "[DRY RUN] Dependent post-processing command:"
    printf "  %q" "${POST_CMD_BASE[@]}" "--dependency=afterany:<ARRAY_JOB_ID>" "${SCRIPT_DIR}/run_global_post.sbatch"; echo ""
    if [[ -n "$DB_ENV_ABS" ]]; then
        echo "[DRY RUN] Dependent unified annotation command:"
        printf "  %q" "${ANN_CMD_BASE[@]}" "--dependency=afterok:<POST_JOB_ID>" "${SCRIPT_DIR}/run_annotate.sbatch"; echo ""
    fi
    exit 0
fi

if ! command -v sbatch >/dev/null 2>&1; then
    echo "ERROR: 'sbatch' not found on PATH. Run on your HPC login node or pass --dry-run." >&2
    exit 1
fi

ARR_JOB_ID="$("${ARRAY_CMD[@]}")"
POST_JOB_ID="$("${POST_CMD_BASE[@]}" --dependency="afterany:${ARR_JOB_ID}" "${SCRIPT_DIR}/run_global_post.sbatch")"
ANN_JOB_ID=""
if [[ -n "$DB_ENV_ABS" ]]; then
    ANN_JOB_ID="$("${ANN_CMD_BASE[@]}" --dependency="afterok:${POST_JOB_ID}" "${SCRIPT_DIR}/run_annotate.sbatch")"
fi

echo ""
echo "Submitted!"
echo "  Array job ID : ${ARR_JOB_ID}"
echo "  Post job ID  : ${POST_JOB_ID} (runs after array ${ARR_JOB_ID} finishes)"
[[ -n "$ANN_JOB_ID" ]] && echo "  Annot job ID : ${ANN_JOB_ID} (runs after post job ${POST_JOB_ID} succeeds)"
echo ""
echo "Monitor with:"
echo "  squeue -u \$USER"
echo "  tail -f ${LOG_DIR}/argj_global_${ARR_JOB_ID}_1.out"
echo "  cat ${OUT_ABS}/comparison/global_cmp_summary.tsv   # once post job finishes"
[[ -n "$ANN_JOB_ID" ]] && echo "  cat ${OUT_ABS}/annotation/annotation_comparison_summary.tsv"
