#!/usr/bin/env bash
# One-time HPC setup script to download and index the free public reference databases
# used by `hpc/annotate_flanks.py` (and KMA pre-screening in `hpc/submit_global_benchmark.sh`).
#
# Usage:
#   bash hpc/setup_annotation_dbs.sh --db-dir /scratch/$USER/argjacent_dbs [--with-genomad]
#
# Writes `<db-dir>/db_paths.env`, which `hpc/run_annotate.sbatch` sources automatically.

set -euo pipefail

DB_DIR=""
WITH_GENOMAD=0
THREADS=4

usage() {
    cat <<'EOF'
Usage: bash hpc/setup_annotation_dbs.sh --db-dir DIR [--with-genomad] [--threads N]

Downloads and indexes:
  1. UniVec + UniVec_Core (NCBI cloning/sequencing vectors for reagent-contamination audit)
  2. ResFinder nucleotide DB (plus optional KMA index if `kma_index` is installed)
  3. PlasmidFinder replicon DB
  4. ISfinder nucleotide sequences (public curated mirror)
  5. Optional: geNomad database (--with-genomad, ~3 GB; requires `genomad` on PATH)

Writes <DIR>/db_paths.env with ready-to-source variables for hpc/run_annotate.sbatch.
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --db-dir)       DB_DIR="$2"; shift 2 ;;
        --with-genomad) WITH_GENOMAD=1; shift ;;
        --threads)      THREADS="$2"; shift 2 ;;
        -h|--help)      usage; exit 0 ;;
        *)              echo "Unknown option: $1" >&2; usage; exit 1 ;;
    esac
done

if [[ -z "$DB_DIR" ]]; then
    echo "ERROR: --db-dir is required." >&2
    usage
    exit 1
fi

mkdir -p "$DB_DIR"/{univec,resfinder,plasmidfinder,isfinder,mobileog,genomad}
DB_ABS="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$DB_DIR")"

dl() {
    local url="$1" dst="$2"
    if command -v curl >/dev/null 2>&1; then
        curl -fL --retry 3 --connect-timeout 30 -sS -o "$dst" "$url"
    elif command -v wget >/dev/null 2>&1; then
        wget -q --tries=3 --timeout=30 -O "$dst" "$url"
    else
        echo "ERROR: need curl or wget to download $url" >&2
        exit 1
    fi
}

echo "=== Setting up ARGjacent annotation databases in ${DB_ABS} ==="

# 1. NCBI UniVec (cloning & expression vectors)
UNIVEC_FA="${DB_ABS}/univec/UniVec.fa"
if [[ ! -s "$UNIVEC_FA" ]]; then
    echo "[1/5] Downloading NCBI UniVec..."
    dl "https://ftp.ncbi.nlm.nih.gov/pub/UniVec/UniVec" "$UNIVEC_FA"
else
    echo "[1/5] UniVec already exists: ${UNIVEC_FA}"
fi

# 2. ResFinder nucleotide DB
RES_FA="${DB_ABS}/resfinder/resfinder.fa"
if [[ ! -s "$RES_FA" ]]; then
    echo "[2/5] Cloning CGE ResFinder database..."
    rm -rf "${DB_ABS}/resfinder/repo"
    git clone --depth 1 https://bitbucket.org/genomicepidemiology/resfinder_db.git "${DB_ABS}/resfinder/repo"
    cat "${DB_ABS}/resfinder/repo"/*.fsa > "$RES_FA"
else
    echo "[2/5] ResFinder already exists: ${RES_FA}"
fi
if command -v kma_index >/dev/null 2>&1 && [[ ! -s "${DB_ABS}/resfinder/resfinder_kma.name" ]]; then
    echo "      Indexing ResFinder for KMA..."
    kma_index -i "$RES_FA" -o "${DB_ABS}/resfinder/resfinder_kma" >/dev/null
fi

# 3. PlasmidFinder replicon DB
PF_FA="${DB_ABS}/plasmidfinder/plasmidfinder.fa"
if [[ ! -s "$PF_FA" ]]; then
    echo "[3/5] Cloning CGE PlasmidFinder database..."
    rm -rf "${DB_ABS}/plasmidfinder/repo"
    git clone --depth 1 https://bitbucket.org/genomicepidemiology/plasmidfinder_db.git "${DB_ABS}/plasmidfinder/repo"
    cat "${DB_ABS}/plasmidfinder/repo"/*.fsa > "$PF_FA"
else
    echo "[3/5] PlasmidFinder already exists: ${PF_FA}"
fi

# 4. ISfinder nucleotide FASTA
IS_FA="${DB_ABS}/isfinder/IS.fna"
if [[ ! -s "$IS_FA" ]]; then
    echo "[4/5] Downloading ISfinder sequences (IS.fna)..."
    dl "https://raw.githubusercontent.com/thanhleviet/ISfinder-sequences/master/IS.fna" "$IS_FA"
else
    echo "[4/5] ISfinder already exists: ${IS_FA}"
fi

# Build BLAST nucleotide indexes if makeblastdb is available
if command -v makeblastdb >/dev/null 2>&1; then
    echo "      Building BLAST nucleotide indexes..."
    for f in "$UNIVEC_FA" "$RES_FA" "$PF_FA" "$IS_FA"; do
        [[ -s "${f}.nin" ]] || makeblastdb -in "$f" -dbtype nucl -out "$f" >/dev/null
    done
fi

# 5. Optional geNomad database
GENOMAD_DB=""
if [[ "$WITH_GENOMAD" == "1" ]]; then
    if command -v genomad >/dev/null 2>&1; then
        echo "[5/5] Downloading geNomad database (~3 GB)..."
        genomad download-database "${DB_ABS}/genomad"
        GENOMAD_DB="${DB_ABS}/genomad/genomad_db"
    else
        echo "[5/5] WARNING: --with-genomad requested but 'genomad' not found on PATH; skipping."
    fi
else
    echo "[5/5] Skipping geNomad download (pass --with-genomad to fetch it)."
fi

# Write ready-to-source environment manifest
ENV_FILE="${DB_ABS}/db_paths.env"
cat > "$ENV_FILE" <<EOF
# Auto-generated by hpc/setup_annotation_dbs.sh
export UNIVEC_DB="${UNIVEC_FA}"
export ARG_DB="${RES_FA}"
export KMA_DB="${DB_ABS}/resfinder/resfinder_kma"
export KMA_REF_FA="${RES_FA}"
export PLASMIDFINDER_DB="${PF_FA}"
export ISFINDER_DB="${IS_FA}"
export GENOMAD_DB="${GENOMAD_DB}"
# Optional manual additions (download mobileOG-db Beatrix FASTA + DIAMOND index, and GTDB Kraken2 DB):
#   diamond makedb --in mobileOG-db_beatrix-1.6.All.faa -d ${DB_ABS}/mobileog/mobileOG.dmnd
export MOBILEOG_DB=""
export KRAKEN2_DB=""
export MMSEQS_TAX_DB=""
EOF

echo ""
echo "=== Setup complete! ==="
echo "  DB env file : ${ENV_FILE}"
echo "  Optional    : Add mobileOG-db (.dmnd) and Kraken2/GTDB paths in ${ENV_FILE} for Layers 2c and 4."
echo "  Next step   : sbatch --export=ALL,OUT_DIR=/scratch/\$USER/argj_global,MANIFEST_TSV=global.tsv,DB_ENV=${ENV_FILE} hpc/run_annotate.sbatch"
